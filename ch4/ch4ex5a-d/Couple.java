public class Couple {
    private final Person bride;
    private final Person groom;

    public Couple(Person bride, Person groom) {
        this.bride = bride;
        this.groom = groom;
    }

    public Person getBride() {
        return bride;
    }

    public Person getGroom() {
        return groom;
    }
}
